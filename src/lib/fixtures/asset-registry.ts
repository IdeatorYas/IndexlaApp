export function getAssetNetworkLabel(assetId: string): string {
  const id = assetId.toLowerCase();
  if (ASSET_NETWORKS[id]) return ASSET_NETWORKS[id];
  if (/^[a-z]{2,5}$/.test(id) && id.length <= 5 && !id.includes("on")) {
    return "Crypto";
  }
  return "Multi-chain";
}
