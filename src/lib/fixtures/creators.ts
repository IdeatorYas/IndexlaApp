function toDirectory(seeds: Seed[]): CreatorDirectoryEntry[] {
  const ranked = [...seeds].sort(
    (a, b) =>
      b.followerCount + b.totalAumUsd / 10_000 -
      (a.followerCount + a.totalAumUsd / 10_000),
  );
  return ranked.map((seed, index) => ({
    ...seed,
    avatarInitials: initials(seed.displayName),
    avatarHue: seed.avatarHue ?? (index * 37) % 360,
    discoveryRank: index + 1,
    isIllustrative: true,
  }));
}

