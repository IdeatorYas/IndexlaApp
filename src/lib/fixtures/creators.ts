export function getCreatorsWorkspace(): CreatorsWorkspace {
  return {
    creators: DIRECTORY,
    featuredHandles: DIRECTORY.filter((c) => c.featured).map((c) => c.handle),
    viewerHubStatus: "not-started",
    specialties: SPECIALTIES,
    networks: NETWORKS,
    isIllustrative: true,
  };
}

export function getEmptyCreatorsWorkspace(): CreatorsWorkspace {
  const base = getCreatorsWorkspace();
  return {
    ...base,
    creators: [],
    featuredHandles: [],
  };
}

export function getCreatorDirectoryByHandle(
  handle: string,
): CreatorDirectoryEntry | undefined {
  return DIRECTORY.find(
    (c) => c.handle.toLowerCase() === handle.toLowerCase(),
  );
}

/** Maps directory entries into legacy CreatorProfile for shared getCreators(). */
export function creatorsAsProfiles(): CreatorProfile[] {
  return DIRECTORY.map((c) => ({
    handle: c.handle,
    displayName: c.displayName,
    bio: c.bio,
    verified: c.verified,
    followerCount: c.followerCount,
    publicPortfolioCount: c.publicProductCount,
    totalAumUsd: c.totalAumUsd,
    bestPortfolioRank: c.discoveryRank <= 10 ? c.discoveryRank : null,
    creatorSince: c.creatorSince,
    activationStatus: "approved" as const,
  }));
}
